export function Kpi({ label, value, ev, hint, tone = "default" }: { label: string; value: ReactNode; ev?: Evidence; hint?: string; tone?: "default" | "warn" | "bad" | "good" }) {
  return (
    <div className="panel p-4">
      <div className="flex items-center justify-between gap-2"><span className="text-xs text-muted-foreground">{label}</span>{ev && <Ev s={ev} />}</div>
      <div className={cn("font-kpi text-2xl md:text-[28px] mt-1.5", tone === "bad" && "text-destructive", tone === "warn" && "text-warning-foreground", tone === "good" && "text-forest")}>{value}</div>
      {hint && <div className="text-[11px] text-muted-foreground mt-1">{hint}</div>}
    </div>
  );
}

export function Pill({ v }: { v: string }) {
  const bad = /Critical|Fail|Blocked|RTO|Invalid|Missed|Escalated|High|Disputed|Flagged|broken/i.test(v);
  const warn = /Watch|Medium|Insufficient|Investigating|Raised|Pending|Open|Hold|Awaiting|Unchecked|Mitigating/i.test(v);
  const good = /Normal|Pass|Delivered|Valid|Resolved|Verified|Approved|Received|Graded|Low|Dispatched|Picked|Unlocked/i.test(v);
  return <span className={cn("inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-[11px] font-medium whitespace-nowrap",
    bad ? "bg-destructive/10 text-destructive" : warn ? "bg-warning/15 text-warning-foreground" : good ? "bg-sage text-forest" : "bg-muted text-muted-foreground")}>{v}</span>;
}

export const short = (h: string) => `${h.slice(0, 8)}…${h.slice(-6)}`;
export const fmt = (n: number, d = 0) => n.toLocaleString("en-IN", { maximumFractionDigits: d, minimumFractionDigits: d });

export function LedgerMini({ pillar, limit = 5 }: { pillar?: Pillar; limit?: number }) {
  const ledger = useSim((s) => s.ledger);
  const rows = ledger.filter((b) => !pillar || b.pillar === pillar).slice(0, limit);
  return (
    <Panel title="ChainTrust audit trail" sub={pillar ? `${pillar} events, hash-chained` : "Latest hash-chained events"} right={<ShieldCheck className="size-4 text-primary" />}>
      {rows.length === 0 ? <p className="text-xs text-muted-foreground">No events yet — run an action to write the first block.</p> : (
        <ol className="space-y-2">
          {rows.map((b) => (
            <li key={b.block} className="flex items-start gap-2 text-xs">
              <Link2 className="size-3.5 mt-0.5 text-primary shrink-0" />
              <div className="min-w-0 flex-1">
                <div className="flex justify-between gap-2"><span className="font-medium truncate">#{b.block} · {b.type}</span><Pill v={b.verified ? "Verified" : "Flagged"} /></div>
                <div className="font-mono text-[10px] text-muted-foreground truncate">{b.entity} · {short(b.hash)}</div>
              </div>
            </li>
          ))}
        </ol>
      )}
    </Panel>
  );
}

export function download(name: string, data: unknown) {
  const txt = typeof data === "string" ? data : JSON.stringify(data, null, 2);
  const url = URL.createObjectURL(new Blob([txt], { type: name.endsWith(".csv") ? "text/csv" : "application/json" }));
  const a = document.createElement("a"); a.href = url; a.download = name; a.click(); URL.revokeObjectURL(url);
}
export const toCsv = (rows: Record<string, unknown>[]) => rows.length ? [Object.keys(rows[0]).join(","), ...rows.map((r) => Object.values(r).map((v) => `"${String(v).replace(/"/g, '""')}"`).join(","))].join("\n") : "";


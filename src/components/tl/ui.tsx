export type Evidence = "CASE" | "DERIVED" | "EXTERNAL" | "ASSUMPTION" | "MODELED";
const EV_TIP: Record<Evidence, string> = {
  CASE: "Directly reported in the case.", DERIVED: "Calculated from case facts (conditional).", EXTERNAL: "Public industry reference, not Threadline actual.",
  ASSUMPTION: "Management/model input — not verified company data.", MODELED: "Generated by the digital twin from current settings.",
};
export function Ev({ s }: { s: Evidence }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span className={cn("inline-flex items-center rounded px-1.5 py-0.5 text-[9px] font-semibold tracking-wider font-display cursor-help",
          s === "CASE" ? "bg-forest text-primary-foreground" : s === "DERIVED" ? "bg-sage text-forest" : s === "MODELED" ? "bg-primary/15 text-forest" : s === "EXTERNAL" ? "bg-muted text-muted-foreground border" : "bg-warning/20 text-warning-foreground")}>{s}</span>
      </TooltipTrigger>
      <TooltipContent className="max-w-xs text-xs">{EV_TIP[s]}</TooltipContent>
    </Tooltip>
  );
}

